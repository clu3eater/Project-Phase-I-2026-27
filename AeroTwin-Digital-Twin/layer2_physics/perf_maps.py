def _volumetric_efficiency(rpm: float, altitude_ft: float, engine: dict) -> float:
    """eta_vol(RPM, altitude) -- MAP 3.

    Shape: a parabola in engine speed peaking near the torque peak (intake
    tuning), scaled by an altitude term.

    eta_vol here is referenced to MANIFOLD conditions -- the turbocharger and
    intercooler raising charge density are handled in ``turbo.py``. The
    sea-level value is not assumed: it is derived from the manufacturer's
    published airflow-to-power relation together with the published target
    manifold pressure and manifold-air-temperature band (see the engine YAML).
    PRD Part 1 section 5.1 MAP 3 quotes 0.85-0.90 at sea level, but those are
    naturally-aspirated-referenced figures for a different engine.
    """
    eta_sl = float(engine["intake"]["volumetric_efficiency_sea_level"])
    rpm_peak = float(engine["ratings"]["max_torque_rpm"])
    # Normalised speed term: 1.0 at the torque peak, falling either side.
    x = (rpm - rpm_peak) / rpm_peak
    speed_term = 1.0 - 0.55 * x * x - 0.10 * max(0.0, x) ** 3
    speed_term = max(0.45, speed_term)

    # Altitude term. Where the engine has a manufacturer performance table the
    # lapse comes from it: full-throttle airflow (the manual's own closure
    # relation) against printed plenum density gives -9 % at 15,000 ft and
    # -13.5 % at 23,000 ft, and the fuel-flow column agrees. The PRD anchors
    # (0.875 -> 0.775 -> 0.625) describe a naturally aspirated engine and fell
    # twice as fast, which starved the modelled air path at altitude.
    om_ratio = om_table.eta_vol_altitude_ratio(engine, altitude_ft)
    if om_ratio is not None:
        alt_term = om_ratio
    else:
        alt_km = altitude_ft / 3280.84
        alt_term = 1.0 - 0.0387 * alt_km - 0.00090 * alt_km * alt_km
    alt_term = max(0.45, alt_term)
    return float(np.clip(eta_sl * speed_term * alt_term, 0.30, 0.98))


def _bmep_wot(rpm: float, engine: dict) -> float:
    """Wide-open-throttle BMEP [bar] at sea level, from the torque curve.

    The WOT curve is the engine's *maximum boost* schedule -- the take-off
    rating. It is pinned to two manufacturer anchors:

        peak torque   171.9 Nm at 5500 rpm  (derived from 99 kW max continuous)
        rated power   104.0 kW at 5800 rpm  (=> 171.2 Nm)

    On this engine max continuous IS a wide-open-throttle point: EASA TCDS
    E.121 section 6 states it is available "up to critical altitude of
    15000 ft", i.e. it is limited by the wastegate boost schedule rather than
    by the throttle plate. Both certified ratings therefore lie on this one
    curve.
    """
    disp = float(engine["geometry"]["displacement_total_L"])
    t_peak = float(engine["ratings"]["max_torque_Nm"])
    rpm_tpeak = float(engine["ratings"]["max_torque_rpm"])
    rpm_ppeak = float(engine["ratings"]["max_power_rpm"])
    p_rated_kw = float(engine["ratings"]["max_power_kW"])

    # Torque at rated-power speed, implied by the rated power anchor.
    t_at_rated = p_rated_kw * 1000.0 * 60.0 / (2.0 * math.pi * rpm_ppeak)

    if rpm <= rpm_tpeak:
        # Rising branch: low-speed torque limited by breathing and by the boost
        # threshold. 0.62 of peak at 1000 rpm is typical for a turbo engine
        # below its boost threshold. Smoothstep gives zero slope at the peak.
        frac_low = 0.62
        u = (rpm - RPM_AXIS[0]) / max(1.0, rpm_tpeak - RPM_AXIS[0])
        u = float(np.clip(u, 0.0, 1.0))
        torque = t_peak * (frac_low + (1.0 - frac_low) * (3 * u**2 - 2 * u**3))
    else:
        # Falling branch: linear between the torque peak and the rated-power
        # point, extrapolated with the same slope beyond redline.
        u = (rpm - rpm_tpeak) / max(1.0, rpm_ppeak - rpm_tpeak)
        torque = t_peak + (t_at_rated - t_peak) * u

    return bmep_from_torque(max(torque, 0.0), disp)


def throttle_for_power(
    maps: PerformanceMaps, target_kw: float, rpm: float, altitude_ft: float
) -> float | None:
    """Throttle percentage that produces ``target_kw`` at a speed and altitude.

    Bisection on the monotonic throttle-power relation. Returns ``None`` when
    the target is outside the achievable range -- used both by the anchor check
    and by the what-if engine when the operator asks for a power setting.
    """
    lo, hi = float(THROTTLE_AXIS[0]), float(THROTTLE_AXIS[-1])
    if maps.power_at(rpm, hi, altitude_ft) < target_kw:
        return None
    if maps.power_at(rpm, lo, altitude_ft) > target_kw:
        return None
    for _ in range(60):
        mid = 0.5 * (lo + hi)
        if maps.power_at(rpm, mid, altitude_ft) < target_kw:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)


def _throttle_factor(throttle_pct: float, rpm: float) -> float:
    """Fraction of WOT BMEP delivered at a part-throttle setting.

    Part-load BMEP is not linear in throttle angle: the throttle is a
    restriction, so the first 50% of travel does most of the work, and pumping
    losses (PMEP) subtract a roughly constant amount that dominates at idle.
    Modelled as an effective-area curve minus a speed-dependent pumping term.
    """
    a = throttle_pct / 100.0
    # Effective flow area of a butterfly: sin-like opening characteristic.
    area = math.sin(0.5 * math.pi * a) ** 1.35
    # Pumping loss grows with speed and with throttling (low area).
    pmep_frac = 0.055 * (rpm / 5500.0) * (1.0 - area)
    return float(np.clip(area - pmep_frac, 0.0, 1.0))


def _altitude_bmep_factor(
    altitude_ft: float, engine: dict, rpm: float = 5500.0, throttle_fraction: float = 1.0
) -> float:
    """Altitude correction on BMEP *including* turbocharger compensation, at ISA.

    Where the engine has a manufacturer performance table the correction IS
    the table: power at this altitude over power at sea level, at the same
    speed and the same throttle position (the lever placed on the manual's
    scale by its sea-level power fraction). That covers throttled operation
    too, which the analytic knee below never did -- at a fixed part-throttle
    position the manual shows power falling with altitude long before the
    turbocharger runs out.

    Without a table: below the critical altitude the wastegate bleeds exhaust
    and the compressor holds manifold pressure, so BMEP is nearly flat; above
    it BMEP falls with ambient pressure. Against the Rotax table that form
    read up to 38 % low at 23,000 ft (review PHY-01); it is kept only for
    engine definitions that have no table.
    """
    turbo = engine.get("turbocharger", {})
    if not turbo.get("fitted", False):
        return atm.ambient_at(altitude_ft).density_ratio
    if om_table.table_for(engine) is not None:
        return om_table.envelope(engine, rpm, throttle_fraction, altitude_ft, 0.0).power

    crit = float(turbo["critical_altitude_ft"])
    # EASA TCDS E.121 section 6 for the 915 iS: "Max. continuous performance at
    # sea level pressure altitude UP TO CRITICAL ALTITUDE of 15000 ft". The
    # rating is held, not merely approached, so the droop below the critical
    # altitude is small -- only the intercooler's residual charge heating and
    # the volumetric-efficiency roll-off.
    droop = 0.05
    if altitude_ft <= crit:
        return 1.0 - droop * (altitude_ft / crit) ** 1.7
    amb_c = atm.ambient_at(crit)
    amb_h = atm.ambient_at(altitude_ft)
    return (1.0 - droop) * (amb_h.pressure_ratio / amb_c.pressure_ratio)


def _bsfc(rpm: float, bmep_bar: float, engine: dict) -> float:
    """Brake specific fuel consumption [g/kWh] -- MAP 2.

    The classic BSFC island: a minimum at moderate speed and high-but-not-peak
    load, rising steeply at low load (friction and pumping dominate a small
    indicated output) and rising again at high load (mixture enrichment for
    knock and thermal protection) and at high speed (friction).
    PRD Part 1 section 5.1 MAP 2: normal range 280-350 g/kWh.
    """
    bsfc_min = 278.0  # g/kWh at the island centre
    rpm_opt = 0.62 * float(engine["ratings"]["max_power_rpm"])  # ~3600 rpm
    bmep_opt = 0.72 * _bmep_wot(rpm_opt, engine)

    speed_pen = 62.0 * ((rpm - rpm_opt) / rpm_opt) ** 2
    load_ratio = max(bmep_bar, 0.4) / max(bmep_opt, 0.4)
    # Low-load penalty ~ 1/load (friction share of indicated work).
    low_load_pen = 105.0 * (1.0 / load_ratio - 1.0) if load_ratio < 1.0 else 0.0
    # High-load enrichment penalty.
    high_load_pen = 90.0 * (load_ratio - 1.0) ** 2 if load_ratio > 1.0 else 0.0
    return float(bsfc_min + speed_pen + low_load_pen + high_load_pen)


def _cht_rise(power_pct: float, oat_c: float, airspeed_kmh: float, engine: dict) -> float:
    """CHT rise above coolant temperature [K] -- MAP 4.

    Heat rejected to the head scales with power; the head-to-coolant path is a
    convective resistance that improves with ram air. PRD Part 1 section 5.1
    MAP 4 axes: power setting x OAT x airspeed.

    CALIBRATION NOTE. The reference engine has LIQUID-COOLED cylinder heads
    (EASA TCDS E.121 section 2), so the head metal sits only 20-30 K above the
    coolant even at full power. An air-cooled engine would show 100 K or more.
    Using an air-cooled rise here would put modelled CHT above the 135 degC
    limit at every cruise setting.
    """
    ram = float(engine["thermal"]["ram_air_cooling_coeff"])
    # Convective conductance improves with ram airflow (roughly V^0.8 for
    # forced convection over the jacket and radiator).
    cooling_gain = 1.0 + ram * (airspeed_kmh**0.8 - 100.0**0.8) * 3.2
    cooling_gain = max(0.55, cooling_gain)
    # Base rise at 100% power, 15 C, 150 km/h.
    base = 26.0 * (power_pct / 100.0) ** 0.92
    # Hotter ambient air removes less heat for the same mass flow.
    oat_term = 1.0 + 0.0068 * (oat_c - 15.0)
    return float(base * oat_term / cooling_gain)


def _egt(power_pct: float, phi: float, altitude_ft: float) -> float:
    """EGT [deg C] -- MAP 5.

    EGT peaks at stoichiometric and falls either side (excess air or excess
    fuel both absorb heat). PRD Part 1 section 5.1 MAP 5 and section 3.1:
    cruise baseline 620 C, normal band 550-700 C.
    """
    # Anchored to the reference engine's certified 950 degC EGT limit
    # (OM-915 i A section 2.1): a turbocharged spark engine cruises in the
    # 780-880 degC band and approaches, but does not reach, the limit at full
    # power. The PRD's 550-700 degC band is an air-cooled naturally-aspirated
    # figure and does not apply. See docs/PRD_DEVIATIONS.md DEV-13.
    base = 615.0 + 295.0 * (power_pct / 100.0) ** 0.80
    # Mixture term: parabola peaking slightly rich of stoichiometric (phi~1.05).
    mixture_term = 1.0 - 0.78 * (phi - 1.05) ** 2
    # Less back-pressure and cooler charge at altitude lower EGT slightly.
    alt_term = 1.0 - 0.0042 * (altitude_ft / 1000.0)
    return float(base * mixture_term * alt_term)


