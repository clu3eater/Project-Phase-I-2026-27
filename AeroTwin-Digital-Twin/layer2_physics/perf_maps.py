class _PointLinear:
    """``RegularGridInterpolator(method="linear")`` at ONE point, minus its cost.

    The accessors below ask for one point at a time, and the mean-value model
    asks tens of thousands of times a sortie: every evaluation of its
    derivatives reads the BMEP and BSFC maps. The interpolator validates,
    reshapes and broadcasts its input as an array on every call, and that
    bookkeeping -- not the interpolation -- was most of the time taken to fly a
    mission (measured: 16 of 28 s across 81,136 derivative evaluations).

    This is the same piecewise-linear interpolation on the same grid: the same
    cell search (``searchsorted(side="left") - 1``, clipped to the last cell),
    the same weights, and a multilinear blend of the cell's corners. Inputs are
    already clipped to the grid by the accessors, so there is no extrapolation
    to reproduce. The two differ only in floating-point rounding (they add the
    corner terms in a different order); a test in
    ``layer2_physics/tests/test_physics.py`` holds them together.
    """

    __slots__ = ("axes", "values", "dims")

    def __init__(self, rgi: RegularGridInterpolator) -> None:
        self.axes = [[float(g) for g in axis] for axis in rgi.grid]
        self.values = np.asarray(rgi.values, dtype=float).tolist()
        self.dims = len(self.axes)

    @staticmethod
    def _cell(axis: list, x: float) -> tuple[int, float]:
        i = bisect_left(axis, x) - 1
        if i < 0:
            i = 0
        elif i > len(axis) - 2:
            i = len(axis) - 2
        lo, hi = axis[i], axis[i + 1]
        return i, (x - lo) / (hi - lo)

    def __call__(self, *x: float) -> float:
        v = self.values
        if self.dims == 2:
            i, t = self._cell(self.axes[0], x[0])
            j, u = self._cell(self.axes[1], x[1])
            a, b = v[i], v[i + 1]
            return ((1.0 - t) * ((1.0 - u) * a[j] + u * a[j + 1])
                    + t * ((1.0 - u) * b[j] + u * b[j + 1]))
        i, t = self._cell(self.axes[0], x[0])
        j, u = self._cell(self.axes[1], x[1])
        k, w = self._cell(self.axes[2], x[2])
        a0, a1, b0, b1 = v[i][j], v[i][j + 1], v[i + 1][j], v[i + 1][j + 1]
        a = ((1.0 - u) * ((1.0 - w) * a0[k] + w * a0[k + 1])
             + u * ((1.0 - w) * a1[k] + w * a1[k + 1]))
        b = ((1.0 - u) * ((1.0 - w) * b0[k] + w * b0[k + 1])
             + u * ((1.0 - w) * b1[k] + w * b1[k + 1]))
        return (1.0 - t) * a + t * b


@dataclass
class PerformanceMaps:
    """The five interpolated maps for one engine definition."""

    engine_key: str
    engine: dict

    bmep: RegularGridInterpolator  # (rpm, throttle, altitude) -> bar
    bsfc: RegularGridInterpolator  # (rpm, bmep) -> g/kWh
    eta_vol: RegularGridInterpolator  # (rpm, altitude) -> -
    cht_rise: RegularGridInterpolator  # (power%, oat, airspeed) -> K
    egt: RegularGridInterpolator  # (power%, phi, altitude) -> degC

    # The same five maps, evaluated one point at a time without the array
    # machinery. See `_PointLinear`; the interpolators above stay the reference.
    _fast: dict = field(init=False, repr=False, compare=False)

    def __post_init__(self) -> None:
        self._fast = {name: _PointLinear(getattr(self, name))
                      for name in ("bmep", "bsfc", "eta_vol", "cht_rise", "egt")}

    # ---- convenience accessors (clip to the map domain, never extrapolate) --

    def _clip(self, value: float, axis: np.ndarray) -> float:
        # Plain comparisons rather than np.clip, which costs microseconds on a
        # scalar and is called hundreds of thousands of times a sortie. NaN
        # passes through, as it does through np.clip.
        v = float(value)
        lo, hi = float(axis[0]), float(axis[-1])
        return lo if v < lo else hi if v > hi else v

    def bmep_at(self, rpm: float, throttle_pct: float, altitude_ft: float) -> float:
        return self._fast["bmep"](self._clip(rpm, RPM_AXIS),
                                  self._clip(throttle_pct, THROTTLE_AXIS),
                                  self._clip(altitude_ft, ALTITUDE_AXIS))

    def bsfc_at(self, rpm: float, bmep_bar: float) -> float:
        return self._fast["bsfc"](self._clip(rpm, RPM_AXIS),
                                  self._clip(bmep_bar, BMEP_AXIS))

    def eta_vol_at(self, rpm: float, altitude_ft: float) -> float:
        return self._fast["eta_vol"](self._clip(rpm, RPM_AXIS),
                                     self._clip(altitude_ft, ALTITUDE_AXIS))

    def cht_rise_at(self, power_pct: float, oat_c: float, airspeed_kmh: float) -> float:
        return self._fast["cht_rise"](self._clip(power_pct, POWER_SETTING_AXIS),
                                      self._clip(oat_c, OAT_AXIS),
                                      self._clip(airspeed_kmh, AIRSPEED_AXIS))

    def egt_at(self, power_pct: float, phi: float, altitude_ft: float) -> float:
        return self._fast["egt"](self._clip(power_pct, POWER_SETTING_AXIS),
                                 self._clip(phi, MIXTURE_AXIS),
                                 self._clip(altitude_ft, ALTITUDE_AXIS))

    # ---- derived quantities -------------------------------------------------

    def torque_at(self, rpm: float, throttle_pct: float, altitude_ft: float) -> float:
        disp = float(self.engine["geometry"]["displacement_total_L"])
        return torque_from_bmep(self.bmep_at(rpm, throttle_pct, altitude_ft), disp)

    def power_at(self, rpm: float, throttle_pct: float, altitude_ft: float) -> float:
        return power_kw(self.torque_at(rpm, throttle_pct, altitude_ft), rpm)

    def power_pct_at(self, rpm: float, throttle_pct: float, altitude_ft: float) -> float:
        rated = float(self.engine["ratings"]["max_power_kW"])
        return 100.0 * self.power_at(rpm, throttle_pct, altitude_ft) / rated


def _build(engine_key: str) -> PerformanceMaps:
    engine = config.load_engine(engine_key)

    # MAP 3: eta_vol(rpm, altitude)
    eta_grid = np.array(
        [[_volumetric_efficiency(r, a, engine) for a in ALTITUDE_AXIS] for r in RPM_AXIS]
    )

    # MAP 1: BMEP(rpm, throttle, altitude)
    bmep_grid = np.zeros((len(RPM_AXIS), len(THROTTLE_AXIS), len(ALTITUDE_AXIS)))
    for i, r in enumerate(RPM_AXIS):
        wot = _bmep_wot(r, engine)
        for j, th in enumerate(THROTTLE_AXIS):
            tf = _throttle_factor(th, r)
            for k, alt in enumerate(ALTITUDE_AXIS):
                bmep_grid[i, j, k] = wot * tf * _altitude_bmep_factor(alt, engine, r, tf)

    # MAP 2: BSFC(rpm, bmep)
    bsfc_grid = np.array([[_bsfc(r, b, engine) for b in BMEP_AXIS] for r in RPM_AXIS])

    # MAP 4: CHT rise(power%, oat, airspeed)
    cht_grid = np.zeros((len(POWER_SETTING_AXIS), len(OAT_AXIS), len(AIRSPEED_AXIS)))
    for i, p in enumerate(POWER_SETTING_AXIS):
        for j, t in enumerate(OAT_AXIS):
            for k, v in enumerate(AIRSPEED_AXIS):
                cht_grid[i, j, k] = _cht_rise(p, t, v, engine)

    # MAP 5: EGT(power%, phi, altitude)
    egt_grid = np.zeros((len(POWER_SETTING_AXIS), len(MIXTURE_AXIS), len(ALTITUDE_AXIS)))
    for i, p in enumerate(POWER_SETTING_AXIS):
        for j, phi in enumerate(MIXTURE_AXIS):
            for k, alt in enumerate(ALTITUDE_AXIS):
                egt_grid[i, j, k] = _egt(p, phi, alt)

    def rgi(points, values):
        # 'linear' rather than 'cubic': cubic on a coarse grid can overshoot and
        # produce non-physical values between nodes, and a monitoring system must
        # never invent a limit exceedance that the model does not contain.
        return RegularGridInterpolator(
            points, values, method="linear", bounds_error=False, fill_value=None
        )

    return PerformanceMaps(
        engine_key=engine_key,
        engine=engine,
        bmep=rgi((RPM_AXIS, THROTTLE_AXIS, ALTITUDE_AXIS), bmep_grid),
        bsfc=rgi((RPM_AXIS, BMEP_AXIS), bsfc_grid),
        eta_vol=rgi((RPM_AXIS, ALTITUDE_AXIS), eta_grid),
        cht_rise=rgi((POWER_SETTING_AXIS, OAT_AXIS, AIRSPEED_AXIS), cht_grid),
        egt=rgi((POWER_SETTING_AXIS, MIXTURE_AXIS, ALTITUDE_AXIS), egt_grid),
    )


@functools.lru_cache(maxsize=8)
def maps_for(engine_key: str = "rotax_915is") -> PerformanceMaps:
    """Cached performance maps for an engine definition."""
    return _build(engine_key)


# ---------------------------------------------------------------------------
# Anchor validation -- exercised by layer2_physics/tests/test_perf_maps.py
# ---------------------------------------------------------------------------


def validate_against_anchors(engine_key: str = "rotax_915is") -> dict[str, tuple[float, float]]:
    """Compare the surrogate maps with every published anchor.

    Returns ``{anchor: (expected, actual)}``. The caller asserts tolerances; this
    function deliberately does not, so that it can also be printed as a table in
    the validation report.
    """
    m = maps_for(engine_key)
    e = m.engine
    disp = float(e["geometry"]["displacement_total_L"])

    rated_rpm = float(e["ratings"]["max_power_rpm"])
    cont_rpm = float(e["ratings"]["continuous_power_rpm"])
    tq_rpm = float(e["ratings"]["max_torque_rpm"])

    out: dict[str, tuple[float, float]] = {}
    out["rated_power_kW"] = (
        float(e["ratings"]["max_power_kW"]),
        m.power_at(rated_rpm, 100.0, 0.0),
    )
    out["peak_torque_Nm"] = (
        float(e["ratings"]["max_torque_Nm"]),
        torque_from_bmep(m.bmep_at(tq_rpm, 100.0, 0.0), disp),
    )
    # On this engine max continuous IS a wide-open-throttle rating: it is held
    # by the wastegate boost schedule at 5500 rpm, not by the throttle plate.
    # The anchor is therefore that it is reached at (or just below) full lever.
    cont_throttle = throttle_for_power(
        m, float(e["ratings"]["continuous_power_kW"]), cont_rpm, 0.0
    )
    out["continuous_power_throttle_pct"] = (100.0, cont_throttle if cont_throttle else 0.0)
    # VOLUMETRIC EFFICIENCY -- the PRD's MAP 3 anchors (0.875 sea level, 0.775 at
    # 10,000 ft) are superseded. They describe a naturally-aspirated reference.
    # For this engine eta_vol is DERIVED from manufacturer data: the OM airflow
    # relation fixes the air mass flow at rated power, and the OM's own target
    # manifold pressure and 25-35 degC MAT band fix the charge density, leaving
    # eta_vol = 0.952 as the only consistent value. See docs/PRD_DEVIATIONS.md
    # DEV-19.
    out["eta_vol_sea_level"] = (0.952, m.eta_vol_at(tq_rpm, 0.0))
    # At altitude: from the manufacturer's table where there is one (printed
    # cells, interpolated directly -- not through the fit the map uses), else
    # the PRD-shaped roll-off, ~87 % of the sea-level figure at 10,000 ft.
    printed_eta = om_table.eta_vol_ratio_printed(e, 10000.0)
    out["eta_vol_10kft"] = (
        0.952 * printed_eta if printed_eta is not None else 0.834,
        m.eta_vol_at(tq_rpm, 10000.0),
    )
    # PRD Part 1 section 4.4 gives 0.75 at 10,000 ft for the NATURALLY ASPIRATED
    # case -- that figure is the ISA density ratio (0.738). The turbocharged
    # installation holds most of its power to the critical altitude, so the two
    # cases are checked separately. See docs/PRD_DEVIATIONS.md DEV-3.
    out["naturally_aspirated_ratio_10kft"] = (
        0.75,
        atm.ambient_at(10000.0).density_ratio,
    )
    # Critical altitude is 15,000 ft [TCDS], so at 10,000 ft the engine still
    # holds its full max-continuous rating. The expected ratios were 0.97 and
    # 0.95, a PRD-era estimate; the manufacturer's table prints 1.003 and 1.005
    # (the rating is HELD, and marginally exceeded, up to the critical
    # altitude), and above it the knee the table prints is checked at three
    # points. Expected values are read from printed cells, not the envelope.
    crit_ft = float(e["turbocharger"]["critical_altitude_ft"])

    def wot_ratio(rpm: float, alt: float) -> float:
        return m.power_at(rpm, 100.0, alt) / m.power_at(rpm, 100.0, 0.0)

    printed = om_table.wot_power_ratio_printed
    has_table = om_table.table_for(e) is not None
    out["turbocharged_ratio_10kft"] = (
        printed(e, cont_rpm, 10000.0) if has_table else 0.97,
        wot_ratio(cont_rpm, 10000.0),
    )
    out["turbocharged_ratio_at_critical_alt"] = (
        printed(e, cont_rpm, crit_ft) if has_table else 0.95,
        wot_ratio(cont_rpm, crit_ft),
    )
    if has_table:
        for rpm_a, alt_a in ((rated_rpm, 18999.0), (rated_rpm, 22999.0), (cont_rpm, 22999.0)):
            out[f"om_full_throttle_ratio_{rpm_a:.0f}rpm_{alt_a:.0f}ft"] = (
                printed(e, rpm_a, alt_a), wot_ratio(rpm_a, alt_a))
    # Published closure relation [OM-915 i A section 2.1]:
    #     Observed power [kW] = -6.3264 + 0.0169 * Airflow [g/min]
    # Inverted at the two certified ratings, this says how much air the engine
    # must actually breathe -- an independent check on the whole air path.
    intake = e.get("intake", {})
    if "airflow_power_slope_kW_per_g_min" in intake:
        a0 = float(intake["airflow_power_intercept_kW"])
        a1 = float(intake["airflow_power_slope_kW_per_g_min"])
        need_g_min = (float(e["ratings"]["max_power_kW"]) - a0) / a1
        out["airflow_at_rated_kg_s"] = (need_g_min / 60000.0, _model_airflow(m, rated_rpm, 0.0))
    out["cruise_bsfc_g_per_kWh"] = (300.0, m.bsfc_at(4000.0, 8.0))
    # Evaluated at sea level: the map applies a small altitude reduction, so
    # anchoring at altitude would fold two effects into one check.
    out["egt_at_75pct_sea_level_C"] = (851.0, m.egt_at(75.0, 1.0, 0.0))
    out["egt_at_100pct_sea_level_C"] = (910.0, m.egt_at(100.0, 1.0, 0.0))
    return out


def _model_airflow(m: PerformanceMaps, rpm: float, altitude_ft: float) -> float:
    """Air mass flow [kg/s] the map's eta_vol implies at the published boost target.

    Uses the OM's own scheduled target manifold pressure at this speed, and the
    25-35 degC manifold-air-temperature band the OM quotes those targets at, so
    the check is manufacturer-datum against manufacturer-datum.
    """
    e = m.engine
    turbo_cfg = e.get("turbocharger", {})
    if rpm >= 5800.0:
        map_bar = float(turbo_cfg.get("target_map_at_5800rpm_bar", 1.0))
    else:
        map_bar = float(turbo_cfg.get("target_map_at_5500rpm_bar", 1.0))
    t_man = float(e["intake"]["manifold_temperature_K"])
    rho_man = map_bar * 1e5 / (287.0 * t_man)
    v_disp = float(e["geometry"]["displacement_total_L"]) * 1e-3
    return m.eta_vol_at(rpm, altitude_ft) * v_disp * (rpm / 120.0) * rho_man


